const {chromium} = require(process.argv[2]);
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const base = process.argv[3], cookie = JSON.parse(fs.readFileSync(0, 'utf8'));

(async () => {
    // Browser plugin not available: use installed Playwright and isolated real APIs.
    // Flow: add compact recipe rows -> shared plan -> one custom plan -> atomic save.
    const browser = await chromium.launch({channel:process.env.AI_PANTRY_BROWSER_CHANNEL || 'chrome',headless:true});
    try {
        const context = await browser.newContext({viewport:{width:1440,height:1000}});
        await context.addCookies([cookie]);
        const page=await context.newPage(), errors=[], posts=[];
        page.on('pageerror',e=>errors.push(e.message));
        page.on('console',m=>{if(['error','warning'].includes(m.type()))errors.push(m.text());});
        page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/batches/bulk'))posts.push(r.postDataJSON());});
        await page.goto(base+'/editor-qa');
        assert.equal(await page.title(),'AI Pantry — Meal Planner');
        assert.equal(page.url(),base+'/editor-qa');
        assert(await page.getByRole('heading',{name:'Meal Planner',exact:true}).isVisible());
        const dialog=page.locator('#mealPlannerDialog'), rows=dialog.locator('[data-meal-editor]');
        const row=i=>rows.nth(i), recipe=i=>row(i).locator('[name="recipe_url"]');
        const shared=dialog.locator('[data-meal-shared-form]');
        const custom=i=>row(i).locator('[data-meal-editor-form]');
        const servings=form=>form.locator('[data-schedule-field="household"][data-meal="dinner"]');
        const note=form=>form.locator('[data-schedule-field="notes"]');
        const save=dialog.locator('[data-meal-batch-save]');
        const ready=()=>page.waitForFunction(()=>{const s=document.getElementById('mealPlannerDialog').mealPlanScheduleState;return !s.panel.ui.loading&&s.entries.every(e=>!e.panel?.ui.loading);});
        const open=async()=>{await page.getByRole('button',{name:'Add Meals',exact:true}).click();await ready();};
        const add=()=>dialog.locator('[data-meal-editor-add]').click();
        const notes=async(form,value)=>{if(!await note(form).isVisible())await form.locator('[data-schedule-section="notes"] > summary').click();await note(form).fill(value);};
        const screenshot=async name=>{const dir=process.env.AI_PANTRY_BROWSER_ARTIFACTS;if(dir){fs.mkdirSync(dir,{recursive:true});await page.screenshot({path:path.join(dir,name)});}};
        await open();await recipe(0).selectOption('recipe://bread');
        await shared.getByRole('button',{name:'Household total',exact:true}).click();
        await notes(shared,'Shared prep notes');
        await shared.locator('[data-schedule-section="prep"] > summary').click();
        await shared.locator('[data-schedule-action="add-prep"]').click();
        await shared.locator('[data-schedule-field="prep-date"]').fill('2026-10-04');
        await shared.locator('[data-schedule-field="prep-instruction"]').fill('Prepare all recipes');
        await add();await recipe(1).selectOption('recipe://soup');
        await add();await recipe(2).selectOption('recipe://rice');
        assert.equal(await rows.count(),3);
        assert.equal(await dialog.locator('[data-meal-editor-form]').count(),1,'Only one scheduling form is mounted by default');
        assert.equal(await servings(shared).inputValue(),'8','Additional recipe yields must not overwrite the shared portions');
        assert.equal(await save.textContent(),'Save 3 Meals');
        await shared.getByRole('button',{name:'Date range',exact:true}).click();
        await shared.locator('[data-schedule-field="end-date"]').fill('2026-10-07');
        assert.equal(await save.textContent(),'Save 9 Meals');
        for(let i=0;i<3;i++)assert.match(await row(i).locator('[data-meal-editor-summary]').textContent(),/Uses shared plan.*3 days.*24 servings/);
        const ids=await rows.evaluateAll(nodes=>nodes.map(n=>n.dataset.mealEditor));assert.equal(new Set(ids).size,3);
        // Ingredient selections remain recipe-specific, even for shared scheduling.
        for(let i=0;i<2;i++)await row(i).locator('[data-meal-ingredient-options] > summary').click();
        await row(1).getByRole('radio',{name:'Sunflower'}).check();
        assert(await row(0).getByRole('radio',{name:'Olive'}).isChecked());
        for(let i=0;i<2;i++)await row(i).locator('[data-meal-ingredient-options] > summary').click();
        await dialog.evaluate(e=>{e.scrollTop=0;});await screenshot('merged-meal-plan-dark.png');
        await page.evaluate(()=>document.documentElement.dataset.publicAuthTheme='light');
        assert.equal(await dialog.locator('.app-dialog-card').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(255, 255, 255)');
        await screenshot('merged-meal-plan-light.png');
        await page.evaluate(()=>document.documentElement.dataset.publicAuthTheme='dark');
        await page.setViewportSize({width:390,height:844});
        await screenshot('merged-meal-plan-mobile.png');
        const bounds=await dialog.evaluate(e=>({width:e.clientWidth,scroll:e.scrollWidth,height:e.getBoundingClientRect().height}));
        assert(bounds.scroll<=bounds.width+1);assert(bounds.height<=844);
        await page.setViewportSize({width:1440,height:1000});
        await row(1).locator('[data-meal-editor-customize]').click();
        assert.equal(await dialog.locator('[data-meal-editor-form]').count(),2);
        assert.equal(await servings(custom(1)).inputValue(),'8');
        await custom(1).getByRole('button',{name:'One day',exact:true}).click();
        await custom(1).locator('[data-schedule-field="single-date"]').fill('2026-10-09');
        await servings(custom(1)).fill('3');await notes(custom(1),'Soup only');
        await row(1).locator('[data-meal-editor-customize]').click();
        assert.equal(await custom(1).isVisible(),false);
        await shared.locator('[data-schedule-field="end-date"]').fill('2026-10-06');
        await servings(shared).fill('9');
        assert.equal(await save.textContent(),'Save 5 Meals');
        assert.match(await row(1).locator('[data-meal-editor-summary]').textContent(),/Custom plan.*1 day.*3 servings/);
        await row(1).locator('[data-meal-editor-customize]').click();
        await row(1).locator('[data-meal-editor-reset]').click();
        assert.equal(await dialog.locator('[data-meal-editor-form]').count(),1);
        assert.equal(await save.textContent(),'Save 6 Meals');
        await row(1).locator('[data-meal-editor-customize]').click();
        assert.equal(await servings(custom(1)).inputValue(),'9','Reset rejoins the current shared settings');
        await custom(1).getByRole('button',{name:'One day',exact:true}).click();
        await custom(1).locator('[data-schedule-field="single-date"]').fill('');
        await shared.locator('[data-schedule-field="start-date"]').fill('');
        await row(1).locator('[data-meal-editor-customize]').click();await save.click();
        assert(await dialog.locator('[data-meal-shared-error]').isVisible());
        assert(await custom(1).isVisible());assert.match(await row(1).locator('[data-meal-editor-error]').textContent(),/Recipe 2:.*date/i);
        assert.equal(posts.length,0);assert.equal(await note(shared).inputValue(),'Shared prep notes');
        await shared.locator('[data-schedule-field="start-date"]').fill('2026-10-05');
        await custom(1).locator('[data-schedule-field="single-date"]').fill('2026-10-09');
        await servings(custom(1)).fill('3');await notes(custom(1),'Soup only');
        await recipe(2).selectOption('');await save.click();
        assert.match(await row(2).locator('[data-meal-editor-error]').textContent(),/Recipe 3: Please select a recipe/);
        await recipe(2).selectOption('recipe://rice');
        // Removing the first row leaves both the shared plan and custom recipe intact.
        await row(0).locator('[data-meal-editor-remove]').click();
        assert.equal(await row(0).getAttribute('data-meal-editor'),ids[1]);
        assert.equal(await servings(custom(0)).inputValue(),'3');assert.equal(await servings(shared).inputValue(),'9');
        await add();await recipe(2).selectOption('recipe://bread');await add();
        assert.equal(await save.textContent(),'Save 5 Meals','Blank row is excluded from the total');
        await save.click();await dialog.waitFor({state:'hidden'});
        assert.equal(posts.length,1);assert.equal(posts[0].batches.length,3);
        const plans=Object.fromEntries(posts[0].batches.map(b=>[b.recipe_url,b]));
        assert.equal(plans['recipe://soup'].allocations.length,1);assert.equal(plans['recipe://soup'].allocations[0].planned_servings,3);
        assert.equal(plans['recipe://soup'].ingredient_option_selections.oil,'sunflower');
        assert.equal(plans['recipe://soup'].prep_notes,'Soup only');
        assert.deepEqual(plans['recipe://bread'].allocations,plans['recipe://rice'].allocations);
        assert.equal(plans['recipe://rice'].allocations.length,2);assert.equal(plans['recipe://rice'].allocations[0].planned_servings,9);
        assert.equal(plans['recipe://rice'].prep_notes,'Shared prep notes');assert.equal(plans['recipe://rice'].prep_steps[0].instruction,'Prepare all recipes');
        const meals=async url=>(await(await context.request.get(base+'/api/meal-plan?recipe_url='+encodeURIComponent(url))).json()).meals;
        assert.equal((await meals('recipe://bread')).length,2);assert.equal((await meals('recipe://rice')).length,2);assert.equal((await meals('recipe://soup')).length,1);
        await open();assert.equal(await rows.count(),1);assert.equal(await recipe(0).inputValue(),'');
        await recipe(0).selectOption('recipe://bread');await row(0).locator('[data-meal-editor-customize]').click();
        await dialog.getByRole('button',{name:'Cancel',exact:true}).click();await open();
        assert.equal(await rows.count(),1);assert.equal(await dialog.locator('[data-meal-editor-form]').count(),1);assert.equal(await recipe(0).inputValue(),'');
        await recipe(0).selectOption('recipe://soup');
        let release;const pending=new Promise(resolve=>release=resolve);
        await page.route('**/api/meal-plan/batches/bulk',async route=>{await pending;await route.continue();});
        await save.click();await page.waitForFunction(()=>document.getElementById('mealPlannerDialog').mealPlanScheduleState.saving);
        assert(await recipe(0).isDisabled());assert(await save.isDisabled());
        await page.keyboard.press('Escape');assert(await dialog.isVisible());
        await page.evaluate(()=>{void saveMealPlannerBatch();void saveMealPlannerBatch();});release();
        await dialog.waitFor({state:'hidden'});assert.equal(posts.length,2);await page.unroute('**/api/meal-plan/batches/bulk');
        await open();await recipe(0).selectOption('recipe://soup');await save.click();
        await page.waitForFunction(()=>!document.getElementById('mealPlannerDialog').mealPlanScheduleState.saving);
        assert(await dialog.isVisible());assert.match(await row(0).locator('[data-meal-editor-error]').textContent(),/already planned/i);
        assert.equal((await meals('recipe://soup')).length,2);
        assert.deepEqual(errors.filter(e=>!e.includes('400 (BAD REQUEST)')),[]);
        console.log('PASS: compact rows, one shared plan, live inheritance, independent overrides/reset, validation, atomic payloads, cancel/reopen, duplicate protection, desktop/mobile/themes');
    } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
